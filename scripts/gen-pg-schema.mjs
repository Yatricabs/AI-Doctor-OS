// Generates supabase/schema.sql (Postgres) from the SQLite DDL embedded in
// app/api/_lib/database.ts. Generating instead of hand-transcribing avoids
// transcription errors across 35+ tables.
//
// Translation rules (chosen to require ZERO application-logic changes):
//   DEFAULT (datetime('now'))  -> ISO-8601 UTC text default, matching nowIso() in JS
//   REAL                       -> DOUBLE PRECISION
//   INTEGER (booleans)         -> kept as INTEGER so existing `is_active = 1`
//                                 style comparisons keep working unchanged
import fs from "node:fs";
import path from "node:path";

const src = fs.readFileSync(path.join("app", "api", "_lib", "database.ts"), "utf8");

// Extract the schema template literal: database.exec(`...`)
const m = src.match(/database\.exec\(`([\s\S]*?)`\)/);
if (!m) {
  console.error("FAIL: could not locate database.exec(`...`) schema block");
  process.exit(1);
}
let ddl = m[1];

// ── translate SQLite -> Postgres ──
const ISO_NOW = `to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')`;

let replacements = 0;
ddl = ddl.replace(/DEFAULT\s*\(\s*datetime\('now'\)\s*\)/gi, () => {
  replacements++;
  return `DEFAULT (${ISO_NOW})`;
});

// REAL -> DOUBLE PRECISION (only as a column type, i.e. preceded by whitespace)
let realCount = 0;
ddl = ddl.replace(/(\s)REAL(\s|,|\))/g, (_all, a, b) => {
  realCount++;
  return `${a}DOUBLE PRECISION${b}`;
});

// Postgres has no AUTOINCREMENT / sqlite pragmas in DDL; assert none slipped through.
const leftovers = [];
if (/datetime\(/i.test(ddl)) leftovers.push("datetime(");
if (/AUTOINCREMENT/i.test(ddl)) leftovers.push("AUTOINCREMENT");
if (/\bREAL\b/.test(ddl)) leftovers.push("REAL");

const tables = [...ddl.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map((x) => x[1]);

const header = `-- AI UPCHAR — Postgres schema (Supabase)
-- GENERATED by scripts/gen-pg-schema.mjs from the SQLite DDL. Do not edit by hand;
-- re-run the generator instead.
--
-- Booleans are intentionally INTEGER (0/1) to stay byte-compatible with the existing
-- application SQL (e.g. "WHERE is_active = 1") and JS Boolean(v) coercion.
-- Timestamps are ISO-8601 UTC TEXT to match nowIso() produced by the app.

`;

fs.mkdirSync("supabase", { recursive: true });
fs.writeFileSync(path.join("supabase", "schema.sql"), header + ddl.trim() + "\n", "utf8");

const report = [
  `tables: ${tables.length}`,
  `datetime('now') defaults rewritten: ${replacements}`,
  `REAL -> DOUBLE PRECISION: ${realCount}`,
  `leftover SQLite-isms: ${leftovers.length ? leftovers.join(", ") : "none"}`,
  ``,
  `table list:`,
  ...tables.map((t) => `  ${t}`),
];
fs.writeFileSync("schema-gen-report.txt", report.join("\n"), "utf8");
